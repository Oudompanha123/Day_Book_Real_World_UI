const dict: Record<Lang, Record<MessageKey, string>> = { en, km };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, n: string) => (vars[n] != null ? String(vars[n]) : m));
  return s;
}

export function isMessageKey(k: string): k is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, k);
}

