export function catName(lang: Lang, c: string): string {
  const k = "cat." + c;
  return isMessageKey(k) ? translate(lang, k) : c;
}

export function payName(lang: Lang, p: string): string {
  const k = "pay." + p;
  return isMessageKey(k) ? translate(lang, k) : p;
}

/** Maps an error code from the API to a message key. */
export function errorKey(code: string): MessageKey {
  switch (code) {
    case "bad_credentials": return "auth.errBad";
    case "email_taken": return "auth.errTaken";
    case "password_too_long": return "auth.errLong";
    case "future_date": return "pay.future";
    case "due_before_loan": return "loan.errDue";
    case "amount_too_high": return "err.generic";
    case "already_settled": return "pay.settledAlready";
    case "network": return "err.network";
    default: return "err.generic";
  }
}
